function PlaygroundSortKeys() {
  /** Сброс пересоздаёт все таблицы — каждая возвращается к своей сортировке по умолчанию. */
  const [resetKey, setResetKey] = useState(0);

  const renderVariant = (variant: Variant) => (
    <DemoSection
      key={variant.code}
      code={variant.code}
      title={variant.title}
      description={variant.description}
      pros={variant.pros}
      cons={variant.cons}
    >
      <VariantTables key={resetKey} picker={variant.picker} highlight={variant.highlight} />
    </DemoSection>
  );

  return (
    <Stack gap="xl" p="md">
      <Group gap="sm">
        <GoBackButton path={ROUTE_PATHS.PLAYGROUND} />
        <Title order={2}>Сортировка составных столбцов</Title>
      </Group>

      <Text c="dimmed" fz="sm" maw={760}>
        В таблицах «Управления» в одной ячейке по два значения — регистрация и вход, автор и дата, —
        а заголовок сортирует только по одному, и по какому — не видно. Ось K — как в заголовке
        выбрать ключ, ось H — как в ячейках показать, по чему отсортировано; итог собирается
        комбинацией (K1 + H1). Таблицы на моках сортируются по-настоящему: кликайте по заголовкам.
        Смотрите в обеих темах; всё без пометки «Только песочница» показано так, как пойдёт в
        реализацию.
      </Text>

      <SandboxOnly>
        <Button
          variant="default"
          size="xs"
          leftSection={<ArrowCounterClockwiseIcon />}
          onClick={() => setResetKey((key) => key + 1)}
        >
          Сбросить сортировку во всех таблицах
        </Button>
      </SandboxOnly>

      <AxisHeader
        title="Итог"
        description="Выбранная комбинация на обеих таблицах — так, как она пойдёт в «Управление»."
      />
      {renderVariant(FINAL_VARIANT)}

      <AxisHeader title="Как сейчас" description="Для сравнения." />
      {renderVariant(CURRENT_VARIANT)}

      <AxisHeader
        title="Ось K — выбор ключа"
        description="Как в заголовке выбрать, по какому из значений ячейки сортировать. Подсветки в ячейках нет (H0)."
      />
      {PICKER_VARIANTS.map(renderVariant)}

      <AxisHeader
        title="Ось H — подсветка в ячейках"
        description="Как в самих строках показать, по чему отсортировано. H0 — без подсветки, это K1 выше; остальные показаны на K1, но сочетаются с любым K."
      />
      {HIGHLIGHT_VARIANTS.map(renderVariant)}
    </Stack>
  );
}

export default PlaygroundSortKeys;
